# Path: tools/build_runtime_mods.py
# Purpose: Emit both distinctly named runtime mods from the one shared Lua
# source tree, stamping each artifact's namespace, settings and info.json.

"""Build the deterministic and Laya runtime mods from `factorio_mod/`.

The deterministic artifact is a byte-for-byte copy of the shared source (the
committed `namespace_override.lua`, `settings.lua` and `info.json` already
describe the deterministic runtime), so the source tree remains directly
deployable. The Laya artifact reuses every shared module unchanged and only
overwrites those three stamped files.

Every server enables both artifacts, so the client's enabled mod set is
identical and switching servers never prompts "sync mods with server". The
build is deterministic and independent of which runtime the caller selects:
both artifacts are always emitted from the same source.

Documented API for the live-run-kit stamping tools:
  `build_runtime_mods(source, output)` returns a manifest dict of
  `{mod_name: {"path": str, "tree_sha256": str, "runtime": str}}`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.runtime_namespace import (  # noqa: E402
    DETERMINISTIC_RUNTIME,
    LAYA_RUNTIME,
    RUNTIMES,
    RuntimeNamespace,
    resolve,
)

SHARED_SOURCE = ROOT / "factorio_mod"
DEFAULT_OUTPUT = ROOT / "build" / "runtime_mods"
ALL_RUNTIMES = (DETERMINISTIC_RUNTIME, LAYA_RUNTIME)

# Stamped files that differ from the committed deterministic defaults.
STAMPED_FILES = ("namespace_override.lua", "settings.lua", "info.json")

_INFO_TEMPLATE = {
    "version": "0.2.0",
    "author": "Factorio_Cursor_RL_Agent",
    "factorio_version": "2.1",
    "dependencies": ["base >= 2.1.0"],
}


def _namespace_override_lua(namespace: RuntimeNamespace) -> str:
    prefix = '"' + namespace.command_prefix + '"'
    return (
        "-- Path: {mod}/namespace_override.lua\n"
        "-- Purpose: Runtime identity generated by tools/build_runtime_mods.py.\n"
        "\n"
        "return {{\n"
        '  runtime = "{runtime}",\n'
        '  mod_name = "{mod}",\n'
        "  command_prefix = {prefix},\n"
        '  remote_interface = "{remote}",\n'
        '  output_root = "{output}",\n'
        '  setting_name = "{setting}",\n'
        "  default_active = {active},\n"
        "}}\n"
    ).format(
        mod=namespace.mod_name,
        runtime=namespace.runtime,
        prefix=prefix,
        remote=namespace.remote_interface,
        output=namespace.output_root,
        setting=namespace.setting_name,
        active="true" if namespace.default_active else "false",
    )


def _settings_lua(namespace: RuntimeNamespace) -> str:
    return (
        "-- Path: {mod}/settings.lua\n"
        "-- Purpose: Runtime activation setting generated by tools/build_runtime_mods.py.\n"
        "\n"
        "data:extend({{\n"
        "  {{\n"
        '    type = "bool-setting",\n'
        '    name = "{setting}",\n'
        '    setting_type = "runtime-global",\n'
        "    default_value = {active},\n"
        '    order = "{order}",\n'
        "  }},\n"
        "}})\n"
    ).format(
        mod=namespace.mod_name,
        setting=namespace.setting_name,
        active="true" if namespace.default_active else "false",
        order=namespace.mod_name.replace("_", "-"),
    )


def _info_json(namespace: RuntimeNamespace) -> str:
    payload = {
        "name": namespace.mod_name,
        "version": _INFO_TEMPLATE["version"],
        "title": (
            "Factorio Cursor RL Agent"
            if namespace.runtime == DETERMINISTIC_RUNTIME
            else "Factorio Laya Agent"
        ),
        "author": _INFO_TEMPLATE["author"],
        "factorio_version": _INFO_TEMPLATE["factorio_version"],
        "dependencies": list(_INFO_TEMPLATE["dependencies"]),
        "description": (
            "Deterministic snapshot exporter and authorized ghost/construction "
            "executor for the planning system."
            if namespace.runtime == DETERMINISTIC_RUNTIME
            else "Laya runtime built from the shared deterministic Lua source; "
            "namespaced commands, remote interface and script-output."
        ),
    }
    return json.dumps(payload, indent=2) + "\n"


def _copy_shared(source: Path, destination: Path) -> None:
    if not (source / "control.lua").is_file() or not (source / "info.json").is_file():
        raise FileNotFoundError(f"shared mod source is incomplete: {source}")
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source, destination)


def _write_text(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")


def _tree_sha256(root: Path) -> str:
    """Replicate the server manager's `tree_hash` contract exactly.

    The shell contract is `find . -type f -print0 | LC_ALL=C sort -z |
    xargs -0 sha256sum | sha256sum`, i.e. the sha256 of the concatenated
    `sha256sum` lines (`<hash>  ./relative`) for byte-sorted relative paths.
    """
    files = sorted(
        (p for p in root.rglob("*") if p.is_file()),
        key=lambda p: ("./" + p.relative_to(root).as_posix()).encode("utf-8"),
    )
    lines = []
    for path in files:
        relative = "./" + path.relative_to(root).as_posix()
        lines.append(f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {relative}\n")
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest()


def build_runtime_mods(
    source: Path = SHARED_SOURCE,
    output: Path = DEFAULT_OUTPUT,
    runtimes: tuple[str, ...] = ALL_RUNTIMES,
) -> dict:
    """Emit the requested runtime artifacts and return a hash manifest."""
    source = Path(source)
    output = Path(output)
    unknown = [runtime for runtime in runtimes if runtime not in RUNTIMES]
    if unknown:
        raise ValueError(f"unknown runtimes: {unknown}")
    manifest: dict[str, dict] = {}
    for runtime in runtimes:
        namespace = resolve(runtime)
        destination = output / namespace.mod_name
        _copy_shared(source, destination)
        # Deterministic keeps the committed stamped files verbatim; every other
        # runtime regenerates them from the shared namespace contract.
        if runtime != DETERMINISTIC_RUNTIME:
            _write_text(destination / "namespace_override.lua", _namespace_override_lua(namespace))
            _write_text(destination / "settings.lua", _settings_lua(namespace))
            _write_text(destination / "info.json", _info_json(namespace))
        manifest[namespace.mod_name] = {
            "path": str(destination),
            "runtime": namespace.runtime,
            "tree_sha256": _tree_sha256(destination),
        }
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SHARED_SOURCE)
    parser.add_argument("--source-root", type=Path, help="Frozen repository root; also stages the training mod")
    parser.add_argument("--output", "--output-root", dest="output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--runtime",
        action="append",
        choices=sorted(RUNTIMES),
        help="emit only this runtime (repeatable); default emits both",
    )
    parser.add_argument("--manifest", type=Path, help="write the hash manifest here")
    args = parser.parse_args(argv)

    runtimes = tuple(args.runtime) if args.runtime else ALL_RUNTIMES
    source = args.source_root / "factorio_mod" if args.source_root else args.source
    manifest = build_runtime_mods(source, args.output, runtimes)
    if args.source_root:
        training = args.source_root / "factorio_training_lab"
        if not (training / "info.json").is_file():
            raise ValueError("frozen source root must include factorio_training_lab")
        destination = args.output / "factorio_training_lab"
        _copy_shared(training, destination)
        manifest["factorio_training_lab"] = {"path": str(destination), "runtime": "training",
                                               "tree_sha256": _tree_sha256(destination)}
    if args.manifest:
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
